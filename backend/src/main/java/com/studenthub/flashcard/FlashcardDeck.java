package com.studenthub.flashcard;

import com.studenthub.course.Course;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "flashcard_decks")
class FlashcardDeck {

    @Id
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "course_id", nullable = false, updatable = false)
    private Course course;

    @Column(name = "created_by")
    private UUID createdBy;

    @Column(nullable = false, length = 150)
    private String title;

    @Column(length = 500)
    private String description;

    /** Set when the deck was generated by AI from a material. */
    @Column(name = "source_material_id")
    private UUID sourceMaterialId;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected FlashcardDeck() {
    }

    FlashcardDeck(Course course, UUID createdBy, String title, String description, UUID sourceMaterialId) {
        this.id = UUID.randomUUID();
        this.course = course;
        this.createdBy = createdBy;
        this.title = title;
        this.description = description;
        this.sourceMaterialId = sourceMaterialId;
        this.createdAt = Instant.now();
    }

    UUID getId() {
        return id;
    }

    Course getCourse() {
        return course;
    }

    UUID getCreatedBy() {
        return createdBy;
    }

    String getTitle() {
        return title;
    }

    String getDescription() {
        return description;
    }

    UUID getSourceMaterialId() {
        return sourceMaterialId;
    }
}
