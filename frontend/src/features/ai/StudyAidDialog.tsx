import { BookOpenText, Check, CircleHelp, Layers, RotateCcw, Sparkles, X } from 'lucide-react'
import { useState } from 'react'
import { useNavigate } from 'react-router'
import { Button } from '../../components/Button'
import { Dialog } from '../../components/Dialog'
import { ErrorState } from '../../components/EmptyState'
import { Spinner } from '../../components/Spinner'
import type { Material } from '../../lib/types'
import { useGenerateFlashcards } from '../flashcards/api'
import { useAiStatus, useStudyAid, type Quiz, type StudyAidKind, type Summary } from './api'

export function StudyAidDialog({ material, onClose }: { material: Material; onClose: () => void }) {
  const [kind, setKind] = useState<StudyAidKind | 'flashcards'>('summary')
  const status = useAiStatus()
  const tabs = [
    { id: 'summary', label: 'Summary', icon: BookOpenText },
    { id: 'quiz', label: 'Practice quiz', icon: CircleHelp },
    { id: 'flashcards', label: 'Flashcards', icon: Layers },
  ] as const

  return (
    <Dialog title={material.title} description={`${material.course.code} · ${material.fileName}`} onClose={onClose}>
      <div className="inline-flex rounded-xl bg-slate-100 p-1" role="tablist">
        {tabs.map(({ id, label, icon: Icon }) => (
          <button
            key={id}
            type="button"
            role="tab"
            aria-selected={kind === id}
            onClick={() => setKind(id)}
            className={`inline-flex items-center gap-2 rounded-lg px-3.5 py-1.5 text-sm font-semibold transition ${
              kind === id ? 'bg-white text-slate-900 shadow-sm' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Icon className="size-4" aria-hidden="true" />
            {label}
          </button>
        ))}
      </div>

      <div className="mt-5">
        {kind === 'summary' ? (
          <SummaryTab materialId={material.id} />
        ) : kind === 'quiz' ? (
          <QuizTab materialId={material.id} />
        ) : (
          <FlashcardsTab materialId={material.id} />
        )}
      </div>

      <footer className="mt-6 flex flex-wrap items-center justify-between gap-2 border-t border-slate-100 pt-4 text-xs text-slate-500">
        <span className="inline-flex items-center gap-1.5">
          <Sparkles className="size-3.5 text-indigo-500" aria-hidden="true" />
          Generated by AI from this file. It can make mistakes, so check important facts.
        </span>
        {status.data && (
          <span>
            {status.data.usedToday} of {status.data.dailyLimit} new generations used today
          </span>
        )}
      </footer>
    </Dialog>
  )
}

function SummaryTab({ materialId }: { materialId: string }) {
  const summary = useStudyAid(materialId, 'summary')
  if (summary.isPending) return <Generating what="summary" />
  if (summary.isError) return <ErrorState text={summary.error.message} />
  return <SummaryView summary={summary.data as Summary} />
}

function QuizTab({ materialId }: { materialId: string }) {
  const quiz = useStudyAid(materialId, 'quiz')
  if (quiz.isPending) return <Generating what="quiz" />
  if (quiz.isError) return <ErrorState text={quiz.error.message} />
  return <QuizView quiz={quiz.data as Quiz} />
}

function FlashcardsTab({ materialId }: { materialId: string }) {
  const generate = useGenerateFlashcards()
  const navigate = useNavigate()

  if (generate.isPending) return <Generating what="flashcards" />
  return (
    <div className="flex flex-col items-center gap-3 py-8 text-center">
      <span className="flex size-12 items-center justify-center rounded-2xl bg-violet-50 text-violet-600">
        <Layers className="size-6" aria-hidden="true" />
      </span>
      <p className="max-w-sm font-medium text-slate-900">Turn this file into a flashcard deck for the whole course</p>
      <p className="max-w-sm text-sm text-slate-500">
        Cards are scheduled with spaced repetition, so each one comes back right before you would forget it.
      </p>
      {generate.isError && <p className="text-sm text-red-600">{generate.error.message}</p>}
      <Button
        className="mt-2"
        onClick={() => generate.mutate(materialId, { onSuccess: ({ deckId }) => navigate(`/decks/${deckId}/study`) })}
      >
        <Sparkles className="size-4" aria-hidden="true" />
        Make flashcards and study
      </Button>
    </div>
  )
}

function Generating({ what }: { what: string }) {
  return (
    <div className="flex flex-col items-center gap-3 py-12 text-center" role="status">
      <Spinner className="size-8 text-indigo-600" />
      <p className="font-medium text-slate-900">Reading the material and writing your {what}…</p>
      <p className="text-sm text-slate-500">The first time can take up to a minute. After that it opens instantly.</p>
    </div>
  )
}

function SummaryView({ summary }: { summary: Summary }) {
  return (
    <div className="space-y-6">
      <p className="text-slate-700">{summary.overview}</p>
      <section>
        <h3 className="text-sm font-semibold tracking-wide text-slate-500 uppercase">Key points</h3>
        <ul className="mt-3 space-y-2">
          {summary.keyPoints.map((point) => (
            <li key={point} className="flex gap-3 text-slate-800">
              <Check className="mt-0.5 size-4 shrink-0 text-emerald-600" aria-hidden="true" />
              {point}
            </li>
          ))}
        </ul>
      </section>
      {summary.keyTerms.length > 0 && (
        <section>
          <h3 className="text-sm font-semibold tracking-wide text-slate-500 uppercase">Key terms</h3>
          <dl className="mt-3 grid grid-cols-1 gap-3 sm:grid-cols-2">
            {summary.keyTerms.map(({ term, definition }) => (
              <div key={term} className="rounded-xl bg-slate-50 p-3 ring-1 ring-slate-100">
                <dt className="font-semibold text-slate-900">{term}</dt>
                <dd className="mt-1 text-sm text-slate-600">{definition}</dd>
              </div>
            ))}
          </dl>
        </section>
      )}
    </div>
  )
}

function QuizView({ quiz }: { quiz: Quiz }) {
  const [answers, setAnswers] = useState<Record<number, number>>({})
  const answered = Object.keys(answers).length
  const correct = quiz.questions.filter((question, index) => answers[index] === question.correctOptionIndex).length
  const finished = answered === quiz.questions.length

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between gap-4 rounded-xl bg-indigo-50 px-4 py-3 text-sm">
        <span className="font-medium text-indigo-900" aria-live="polite">
          {finished
            ? `You got ${correct} of ${quiz.questions.length} right${correct === quiz.questions.length ? ' 🎉' : ''}`
            : `${answered} of ${quiz.questions.length} answered`}
        </span>
        {answered > 0 && (
          <Button variant="ghost" size="sm" onClick={() => setAnswers({})}>
            <RotateCcw className="size-3.5" aria-hidden="true" />
            Start over
          </Button>
        )}
      </div>

      <ol className="space-y-6">
        {quiz.questions.map((question, index) => {
          const chosen = answers[index]
          const isAnswered = chosen !== undefined
          return (
            <li key={question.question}>
              <p className="font-semibold text-slate-900">
                {index + 1}. {question.question}
              </p>
              <div className="mt-3 grid grid-cols-1 gap-2" role="group" aria-label={`Answers to question ${index + 1}`}>
                {question.options.map((option, optionIndex) => {
                  const isCorrect = optionIndex === question.correctOptionIndex
                  const tone = !isAnswered
                    ? 'bg-white ring-slate-200 hover:bg-slate-50 hover:ring-indigo-300'
                    : isCorrect
                      ? 'bg-emerald-50 text-emerald-900 ring-emerald-300'
                      : optionIndex === chosen
                        ? 'bg-red-50 text-red-900 ring-red-300'
                        : 'bg-white text-slate-400 ring-slate-100'
                  return (
                    <button
                      key={option}
                      type="button"
                      disabled={isAnswered}
                      onClick={() => setAnswers({ ...answers, [index]: optionIndex })}
                      className={`flex items-center justify-between gap-3 rounded-xl px-4 py-2.5 text-left text-sm ring-1 transition ${tone}`}
                    >
                      {option}
                      {isAnswered && isCorrect && <Check className="size-4 shrink-0" aria-label="Correct answer" />}
                      {isAnswered && optionIndex === chosen && !isCorrect && (
                        <X className="size-4 shrink-0" aria-label="Your answer" />
                      )}
                    </button>
                  )
                })}
              </div>
              {isAnswered && <p className="mt-2 text-sm text-slate-600">{question.explanation}</p>}
            </li>
          )
        })}
      </ol>
    </div>
  )
}
